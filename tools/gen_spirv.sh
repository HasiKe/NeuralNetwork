#!/usr/bin/env sh
# Compile the Vulkan compute shader to SPIR-V and embed it as a C++ header.
# Requires glslc (shaderc) or glslangValidator.
set -eu
cd "$(dirname "$0")/.."
src=src/gpu/sgemm.comp
out=src/gpu/sgemm_spv.inc
tmp=$(mktemp)
if command -v glslc >/dev/null 2>&1; then
    glslc -O --target-env=vulkan1.0 -o "$tmp" "$src"
else
    glslangValidator -V --target-env vulkan1.0 -o "$tmp" "$src"
fi
{
    echo "// Generated by tools/gen_spirv.sh from $src - do not edit."
    od -An -v -tx4 "$tmp" | tr -s ' ' '\n' | grep -v '^$' | sed 's/^/0x/; s/$/,/' | paste -sd ' ' | fold -w 96 -s
} > "$out"
rm -f "$tmp"
echo "wrote $out"
